prueba("nuevo turno conserva reputacion y limpia objetivos", function()
    local s = T.nuevo()
    T.iniciar(s, 1)
    T.registrar(s, 1, 1, 3, 1, true)
    T.cerrar(s, 1)
    local anterior = s.ultimo
    T.elegir(s, "ruta")
    igual(s.destinos, 0)
    T.iniciar(s, 2)
    igual(s.cajas, 0)
    igual(next(s.visitados), nil)
    igual(s.reputacion, 36)
    igual(s.ultimo, anterior)
end)
prueba("jugadores independientes", function()
    local a, b = T.nuevo(), T.nuevo()
    T.iniciar(a, 1)
    T.iniciar(b, 1)
    T.registrar(a, 1, 1, 3, 1, true)
    igual(b.cajas, 0)
    igual(b.destinos, 0)
    igual(next(b.entregasVistas), nil)
end)
prueba("numeros no finitos fuera de rango y fracciones", function()
    local s = T.nuevo()
    T.iniciar(s, 1)
    for _, valor in ipairs({ 0, -1, 1.5, 4, math.huge, 0/0 }) do
        igual(T.registrar(s, 1, 20, valor, 1, false), false)
    end
    for _, valor in ipairs({ 0, -1, 1.5, 9, math.huge, 0/0 }) do
        igual(T.registrar(s, 1, 20, 1, valor, false), false)
    end
    igual(T.registrar(s, 1, 0/0, 1, 1, false), false)
    igual(T.registrar(s, 1, 20, 1, 1, "true"), false)
    igual(s.cajas, 0)
end)
